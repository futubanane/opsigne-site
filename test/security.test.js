'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.join(__dirname, '..');
const SRC = ['sha256', 'chain', 'qa', 'report', 'engine', 'demo', 'site', 'boot'].map((n) => [n, fs.readFileSync(path.join(ROOT, 'js', n + '.js'), 'utf8')]);

test('no dangerous or networked APIs in the shipped JS (innerHTML, eval, Function, fetch, XHR, storage, cookies, WebSocket, beacon...)', () => {
  const banned = /\.innerHTML|\.outerHTML|insertAdjacentHTML|document\.write|\beval\s*\(|new\s+Function|\bFunction\s*\(|setTimeout\s*\(\s*['"`]|\bfetch\s*\(|XMLHttpRequest|WebSocket|sendBeacon|EventSource|importScripts|localStorage|sessionStorage|indexedDB|document\.cookie|caches\b|serviceWorker/;
  for (const [n, s] of SRC) {
    const code = s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
    const m = code.match(banned);
    assert.equal(m, null, n + '.js uses ' + (m && m[0]));
  }
});

test('bundle.js is exactly the concatenation of the sources (regenerate with python3 _build_pages.py)', () => {
  const builder = fs.readFileSync(path.join(ROOT, '_build_pages.py'), 'utf8');
  const order = JSON.parse(builder.match(/JS_ORDER = (\[.*?\])/)[1]);
  const parts = ['/* OPSIGNE bundle - GENERATED by _build_pages.py from js/*.js (order: ' + order.join(', ') + '). Edit the sources, not this file. */'];
  for (const n of order) parts.push(fs.readFileSync(path.join(ROOT, 'js', n + '.js'), 'utf8').replace(/\n+$/, ''));
  assert.equal(fs.readFileSync(path.join(ROOT, 'js', 'bundle.js'), 'utf8'), parts.join('\n') + '\n');
});

test('pages: strict CSP meta (no unsafe-*, no remote origins), no inline script/style/handlers, no external URLs', () => {
  for (const f of ['index.html', 'en/index.html']) {
    const h = fs.readFileSync(path.join(ROOT, f), 'utf8');
    const csp = h.match(/Content-Security-Policy" content="([^"]+)"/)[1];
    assert.match(csp, /default-src 'none'/); assert.match(csp, /connect-src 'none'/); assert.doesNotMatch(csp, /unsafe|https?:|\*/);
    assert.doesNotMatch(h, /<script(?![^>]*\bsrc=)/i, f + ' has an inline script');
    assert.doesNotMatch(h, /\sstyle=|<style|\son[a-z]+=/i, f + ' has inline style or handlers');
    assert.doesNotMatch(h.replace(/mailto:[^"]+/g, ''), /(src|href)="(https?:)?\/\//, f + ' references an external URL');
  }
});

test('report HTML for a tampered run still escapes everything and carries a CSP without script permission', async () => {
  const E = require('../js/engine.js'), doc = require('../data/mop-ups-017.json');
  const run = await E.startRun(doc, '"><svg onload=alert(1)>');
  const rep = await run.report({ lang: 'en', engine: 'x' });
  assert.match(rep.html, /Content-Security-Policy" content="default-src 'none'/);
  assert.doesNotMatch(rep.html, /<svg/i); assert.match(rep.html, /&lt;svg onload=alert\(1\)&gt;/);
});
