#!/usr/bin/env python3
"""Embeds the fictional procedure (EN source + FR rendering) into js/mop-data.js so the demo needs no fetch/XHR
(fetch of local JSON fails from file://). Run: python3 tools/make_fr.py && python3 tools/build_data.py"""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
en = json.load(open(os.path.join(R, "data", "mop-ups-017.json"), encoding="utf-8"))
fr = json.load(open(os.path.join(R, "data", "mop-ups-017.fr.json"), encoding="utf-8"))
js = ("/* GENERATED by tools/build_data.py from data/mop-ups-017*.json - do not edit. Fictional procedure, synthetic data only. */\n"
      "(function (root) {\n  'use strict';\n  var MOP = %s;\n"
      "  if (typeof module !== 'undefined' && module.exports) module.exports = MOP; else { root.OPSIGNE = root.OPSIGNE || {}; root.OPSIGNE.MOP = MOP; }\n"
      "})(typeof window !== 'undefined' ? window : globalThis);\n") % json.dumps({"en": en, "fr": fr}, ensure_ascii=False, separators=(",", ":"))
open(os.path.join(R, "js", "mop-data.js"), "w", encoding="utf-8").write(js)
print("js/mop-data.js", len(js), "bytes")
